#!/usr/bin/env python3
"""Prepare what server/gta_web.py needs from the classic sites.

- <out>/classic/_sites.json : the sites with their local entry page and whether it was downloaded
- <out>/_ruffle/rewrite.js  : rules so the SWFs that ask for absolute URLs
                              (http://www.rockstargames.com/...) load the local copy
- <out>/_ruffle/*           : Ruffle, copied from <ruffle dir>

    python classic/build_hub_data.py classic_sites.json <out> <ruffle dir> [--cache DIR]

--cache is the folder with <GAME>/_manifest/ written by wayback_mirror.py (default: <out>/classic).
"""
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wayback_mirror import local_rel, canon_host  # noqa: E402


def build(sites_file: Path, root: Path, ruffle_src: Path, cache: Path | None = None, log=print):
    sites = json.loads(Path(sites_file).read_text(encoding="utf-8"))
    classic = root / "classic"
    cache = cache or classic
    out = []
    rules = []
    for s in sites:
        rel = local_rel(s["entry"], "text/html")
        local = classic / s["game"] / rel
        man = cache / s["game"] / "_manifest" / f'{s["id"]}.json'
        files, flash = 0, False
        if man.exists():
            rows = json.loads(man.read_text(encoding="utf-8"))["rows"]
            files = sum(1 for r in rows if (classic / s["game"] / local_rel(r["url"], r["mime"])).exists())
            flash = any(r["url"].lower().split("?")[0].endswith(".swf") for r in rows)
        out.append(dict(s, local=f'/{s["game"].lower()}/{rel}', ready=local.exists(), files=files, flash=flash))
        for pre in s["prefixes"]:
            host, _, path = pre.partition("/")
            # JavaScript regex literal: the slash has to be escaped too
            h = re.escape(canon_host(host)).replace("/", "\\/")
            p = re.escape("/" + path).replace("/", "\\/")
            rules.append((len(path), f'[/^https?:\\/\\/(www\\.)?{h}{p}/i, "/{s["game"].lower()}/{canon_host(host)}/{path}"]'))
    classic.mkdir(parents=True, exist_ok=True)
    (classic / "_sites.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    rdir = root / "_ruffle"
    rdir.mkdir(parents=True, exist_ok=True)
    for f in ruffle_src.iterdir():
        if f.is_file():
            shutil.copyfile(f, rdir / f.name)
    rules.sort(key=lambda r: -r[0])  # longest paths first
    js = "// generated by classic/build_hub_data.py\nwindow.GTAWEB_REWRITE = [\n  " + ",\n  ".join(r for _, r in rules) + "\n];\n"
    (rdir / "rewrite.js").write_text(js, encoding="utf-8")
    ready = sum(1 for s in out if s["ready"])
    log(f"{len(out)} sites, {ready} with their entry page downloaded, {len(rules)} rewrite rules")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write _sites.json and the Ruffle folder for the hub.")
    ap.add_argument("sites")
    ap.add_argument("out")
    ap.add_argument("ruffle")
    ap.add_argument("--cache")
    a = ap.parse_args(argv)
    build(Path(a.sites), Path(a.out), Path(a.ruffle), Path(a.cache) if a.cache else None)


if __name__ == "__main__":
    main()
